-- ---------------------------------------------------------------------
-- 3.1 DATA PROFILING - KHÁM PHÁ DỮ LIỆU
-- ---------------------------------------------------------------------

-- Truy vấn 1: Đếm số lượng dòng giữa các tầng kiến trúc
SELECT 'BRONZE.ORDERS' AS ENTITY, COUNT(*) AS TOTAL_RECORDS FROM TPCH_ANALYTICS_DB.STAGING.ORDERS
UNION ALL
SELECT 'SILVER.ORDERS_SILVER', COUNT(*) FROM TPCH_ANALYTICS_DB.ANALYTICS.ORDERS_SILVER
UNION ALL
SELECT 'BRONZE.CUSTOMER', COUNT(*) FROM TPCH_ANALYTICS_DB.STAGING.CUSTOMER
UNION ALL
SELECT 'SILVER.CUSTOMER_SILVER', COUNT(*) FROM TPCH_ANALYTICS_DB.ANALYTICS.CUSTOMER_SILVER
UNION ALL
SELECT 'GOLD.CUSTOMER_LTV', COUNT(*) FROM TPCH_ANALYTICS_DB.ANALYTICS.CUSTOMER_LTV
UNION ALL
SELECT 'GOLD.DAILY_SALES_SUMMARY', COUNT(*) FROM TPCH_ANALYTICS_DB.ANALYTICS.DAILY_SALES_SUMMARY;

-- Truy vấn 2: Phân tích số lượng khách hàng theo quốc gia & khu vực
SELECT 
    C_REGION_NAME AS REGION,
    C_NATION_NAME AS COUNTRY,
    COUNT(DISTINCT C_CUSTKEY) AS CUSTOMER_COUNT,
    ROUND(COUNT(DISTINCT C_CUSTKEY) * 100.0 / SUM(COUNT(DISTINCT C_CUSTKEY)) OVER(), 2) AS PCT_OF_TOTAL
FROM TPCH_ANALYTICS_DB.ANALYTICS.CUSTOMER_SILVER
GROUP BY C_REGION_NAME, C_NATION_NAME
ORDER BY REGION ASC, CUSTOMER_COUNT DESC;

-- Truy vấn 3: Phân tích đơn hàng theo trạng thái (Fulfilled, Open, Pending)
SELECT 
    O_ORDERSTATUS,
    O_ORDERSTATUS_DESC,
    COUNT(*) AS TOTAL_ORDERS,
    SUM(O_TOTALPRICE) AS TOTAL_REVENUE,
    ROUND(AVG(O_TOTALPRICE), 2) AS AVG_ORDER_VALUE,
    ROUND(SUM(O_TOTALPRICE) * 100.0 / SUM(SUM(O_TOTALPRICE)) OVER(), 2) AS REVENUE_SHARE_PCT
FROM TPCH_ANALYTICS_DB.ANALYTICS.ORDERS_SILVER
GROUP BY O_ORDERSTATUS, O_ORDERSTATUS_DESC
ORDER BY TOTAL_ORDERS DESC;

-- Truy vấn 4: Top 10 sản phẩm được bán nhiều nhất (theo số lượng & doanh thu)
SELECT 
    L_PARTKEY,
    L_PART_NAME,
    L_PART_TYPE,
    SUM(L_QUANTITY) AS TOTAL_QUANTITY_SOLD,
    ROUND(SUM(L_FINAL_PRICE), 2) AS TOTAL_SALES_AMOUNT
FROM TPCH_ANALYTICS_DB.ANALYTICS.LINEITEM_SILVER
GROUP BY L_PARTKEY, L_PART_NAME, L_PART_TYPE
ORDER BY TOTAL_QUANTITY_SOLD DESC
LIMIT 10;


-- ---------------------------------------------------------------------
-- 3.2 DATA QUALITY CHECKS 
-- ---------------------------------------------------------------------

-- DQ 1: Kiểm tra NULL trên các cột Primary Key và Foreign Key quan trọng
SELECT 
    'ORDERS_SILVER PK (O_ORDERKEY)' AS CHECK_NAME,
    COUNT(*) AS FAILED_RECORDS
FROM TPCH_ANALYTICS_DB.ANALYTICS.ORDERS_SILVER
WHERE O_ORDERKEY IS NULL

UNION ALL

SELECT 
    'CUSTOMER_SILVER PK (C_CUSTKEY)',
    COUNT(*)
FROM TPCH_ANALYTICS_DB.ANALYTICS.CUSTOMER_SILVER
WHERE C_CUSTKEY IS NULL

UNION ALL

SELECT 
    'LINEITEM_SILVER Composite PK (L_ORDERKEY, L_LINENUMBER)',
    COUNT(*)
FROM TPCH_ANALYTICS_DB.ANALYTICS.LINEITEM_SILVER
WHERE L_ORDERKEY IS NULL OR L_LINENUMBER IS NULL

UNION ALL

SELECT 
    'ORDERS_SILVER FK (O_CUSTKEY)',
    COUNT(*)
FROM TPCH_ANALYTICS_DB.ANALYTICS.ORDERS_SILVER
WHERE O_CUSTKEY IS NULL;

-- DQ 2: Kiểm tra bản ghi trùng lặp (Duplicate Keys)
-- Kết quả trả về 0 dòng nghĩa là không có dữ liệu trùng lặp
SELECT 
    O_ORDERKEY,
    COUNT(*) AS DUPLICATE_COUNT
FROM TPCH_ANALYTICS_DB.ANALYTICS.ORDERS_SILVER
GROUP BY O_ORDERKEY
HAVING COUNT(*) > 1;

SELECT 
    L_ORDERKEY,
    L_LINENUMBER,
    COUNT(*) AS DUPLICATE_COUNT
FROM TPCH_ANALYTICS_DB.ANALYTICS.LINEITEM_SILVER
GROUP BY L_ORDERKEY, L_LINENUMBER
HAVING COUNT(*) > 1;

-- DQ 3: Kiểm tra có đơn hàng nào không tồn tại trong danh mục khách hàng không
SELECT 
    COUNT(*) AS ORPHAN_ORDERS_COUNT
FROM TPCH_ANALYTICS_DB.ANALYTICS.ORDERS_SILVER o
LEFT JOIN TPCH_ANALYTICS_DB.ANALYTICS.CUSTOMER_SILVER c ON o.O_CUSTKEY = c.C_CUSTKEY
WHERE c.C_CUSTKEY IS NULL;

-- DQ 4: Kiểm tra tính hợp lệ logic nghiệp vụ (Business Rules Sanity Check)
SELECT 
    'Invalid Discount (<0 or >1)' AS RULE_DESCRIPTION,
    COUNT(*) AS VIOLATION_COUNT
FROM TPCH_ANALYTICS_DB.ANALYTICS.LINEITEM_SILVER
WHERE L_DISCOUNT < 0 OR L_DISCOUNT > 1

UNION ALL

SELECT 
    'Negative or Zero Quantity',
    COUNT(*)
FROM TPCH_ANALYTICS_DB.ANALYTICS.LINEITEM_SILVER
WHERE L_QUANTITY <= 0

UNION ALL

SELECT 
    'Negative Extended Price',
    COUNT(*)
FROM TPCH_ANALYTICS_DB.ANALYTICS.LINEITEM_SILVER
WHERE L_EXTENDEDPRICE < 0

UNION ALL

SELECT 
    'Receipt Date before Ship Date (Physical impossibility)',
    COUNT(*)
FROM TPCH_ANALYTICS_DB.ANALYTICS.LINEITEM_SILVER
WHERE L_RECEIPTDATE < L_SHIPDATE;


-- ---------------------------------------------------------------------
-- 3.3 PERFORMANCE OPTIMIZATION VỚI EXPLAIN và QUERY PROFILING
-- ---------------------------------------------------------------------

-- Viết một câu truy vấn phân tích tổng hợp phức tạp đa chiều:
-- Phân tích doanh thu và độ trễ giao hàng theo từng phân khúc thị trường và khu vực
EXPLAIN
SELECT 
    c.C_REGION_NAME,
    c.C_MKTSEGMENT,
    o.O_ORDER_YEAR,
    COUNT(DISTINCT o.O_ORDERKEY) AS ORDER_VOLUME,
    SUM(l.L_FINAL_PRICE) AS TOTAL_REVENUE,
    ROUND(AVG(l.L_SHIP_DELAY_DAYS), 2) AS AVG_DELIVERY_DELAY
FROM TPCH_ANALYTICS_DB.ANALYTICS.LINEITEM_SILVER l
JOIN TPCH_ANALYTICS_DB.ANALYTICS.ORDERS_SILVER o 
    ON l.L_ORDERKEY = o.O_ORDERKEY
JOIN TPCH_ANALYTICS_DB.ANALYTICS.CUSTOMER_SILVER c 
    ON o.O_CUSTKEY = c.C_CUSTKEY
WHERE o.O_ORDER_YEAR BETWEEN 1995 AND 1997
GROUP BY c.C_REGION_NAME, c.C_MKTSEGMENT, o.O_ORDER_YEAR
ORDER BY c.C_REGION_NAME, TOTAL_REVENUE DESC;

-- Thực thi câu truy vấn trên để tạo thông tin Query Profile trong Snowsight
SELECT 
    c.C_REGION_NAME,
    c.C_MKTSEGMENT,
    o.O_ORDER_YEAR,
    COUNT(DISTINCT o.O_ORDERKEY) AS ORDER_VOLUME,
    SUM(l.L_FINAL_PRICE) AS TOTAL_REVENUE,
    ROUND(AVG(l.L_SHIP_DELAY_DAYS), 2) AS AVG_DELIVERY_DELAY
FROM TPCH_ANALYTICS_DB.ANALYTICS.LINEITEM_SILVER l
JOIN TPCH_ANALYTICS_DB.ANALYTICS.ORDERS_SILVER o 
    ON l.L_ORDERKEY = o.O_ORDERKEY
JOIN TPCH_ANALYTICS_DB.ANALYTICS.CUSTOMER_SILVER c 
    ON o.O_CUSTKEY = c.C_CUSTKEY
WHERE o.O_ORDER_YEAR BETWEEN 1995 AND 1997
GROUP BY c.C_REGION_NAME, c.C_MKTSEGMENT, o.O_ORDER_YEAR
ORDER BY c.C_REGION_NAME, TOTAL_REVENUE DESC;

-- Kiểm tra lịch sử truy vấn (Query History) để xem thời gian chạy và bytes scanned
SELECT 
    QUERY_ID,
    QUERY_TEXT,
    TOTAL_ELAPSED_TIME / 1000.0 AS ELAPSED_SECONDS,
    BYTES_SCANNED / (1024 * 1024.0) AS MB_SCANNED,
    ROWS_PRODUCED,
    COMPILATION_TIME / 1000.0 AS COMPILATION_SECONDS,
    EXECUTION_TIME / 1000.0 AS EXECUTION_SECONDS
FROM TABLE(INFORMATION_SCHEMA.QUERY_HISTORY(
    RESULT_LIMIT => 5
))
WHERE QUERY_TEXT ILIKE '%AVG_DELIVERY_DELAY%'
ORDER BY START_TIME DESC;