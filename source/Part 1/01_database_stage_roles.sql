-- ---------------------------------------------------------------------
-- 1.1 TẠO ROLES VÀ THIẾT LẬP HỆ THỐNG PHÂN QUYỀN (RBAC)
-- ---------------------------------------------------------------------
USE ROLE SECURITYADMIN;
-- Tạo các roles theo yêu cầu dự án
CREATE ROLE IF NOT EXISTS TPCH_ADMIN;
-- Quản trị toàn bộ dự án
CREATE ROLE IF NOT EXISTS TPCH_DEVELOPER;
-- Load data, transform pipeline
CREATE ROLE IF NOT EXISTS TPCH_ANALYST;
-- Truy vấn dữ liệu, lập báo cáo
CREATE ROLE IF NOT EXISTS TPCH_VIEWER;
-- Chỉ xem các bảng báo cáo
-- Thiết lập phân cấp Role (Role Hierarchy)
GRANT ROLE TPCH_VIEWER TO ROLE TPCH_ANALYST;
GRANT ROLE TPCH_ANALYST TO ROLE TPCH_DEVELOPER;
GRANT ROLE TPCH_DEVELOPER TO ROLE TPCH_ADMIN;
GRANT ROLE TPCH_ADMIN TO ROLE SYSADMIN;
-- ---------------------------------------------------------------------
-- 1.2 TẠO WAREHOUSE, DATABASE VÀ CÁC SCHEMAS
-- ---------------------------------------------------------------------
USE ROLE SYSADMIN;
-- Tạo Virtual Warehouse cho dự án
CREATE WAREHOUSE IF NOT EXISTS TPCH_WH WITH WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 120 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE COMMENT = 'Warehouse cho tác vụ phân tích và pipeline TPC-H';
-- Tạo Database chính
CREATE DATABASE IF NOT EXISTS TPCH_ANALYTICS_DB COMMENT = 'Database chính cho dự án TPC-H Analytics';
USE DATABASE TPCH_ANALYTICS_DB;
-- Tạo các Schemas
CREATE SCHEMA IF NOT EXISTS STAGING COMMENT = 'Bronze Layer: Chứa dữ liệu gốc nạp từ file';
CREATE SCHEMA IF NOT EXISTS ANALYTICS COMMENT = 'Silver & Gold Layer: Dữ liệu đã làm sạch và các bảng tổng hợp';
CREATE SCHEMA IF NOT EXISTS REPORTS COMMENT = 'Chứa Views và Tables phục vụ trực tiếp cho báo cáo/BI';
CREATE SCHEMA IF NOT EXISTS UDFS COMMENT = 'Chứa các hàm tự định nghĩa (User-Defined Functions)';
-- ---------------------------------------------------------------------
-- CẤP QUYỀN (GRANTS) CHO CÁC ROLES
-- ---------------------------------------------------------------------
-- Quyền sử dụng Warehouse
GRANT USAGE ON WAREHOUSE TPCH_WH TO ROLE TPCH_VIEWER;
GRANT USAGE ON WAREHOUSE TPCH_WH TO ROLE TPCH_ANALYST;
GRANT USAGE ON WAREHOUSE TPCH_WH TO ROLE TPCH_DEVELOPER;
GRANT USAGE,
OPERATE ON WAREHOUSE TPCH_WH TO ROLE TPCH_ADMIN;
-- Quyền sử dụng Database
GRANT USAGE ON DATABASE TPCH_ANALYTICS_DB TO ROLE TPCH_VIEWER;
GRANT USAGE ON DATABASE TPCH_ANALYTICS_DB TO ROLE TPCH_ANALYST;
GRANT USAGE ON DATABASE TPCH_ANALYTICS_DB TO ROLE TPCH_DEVELOPER;
GRANT ALL PRIVILEGES ON DATABASE TPCH_ANALYTICS_DB TO ROLE TPCH_ADMIN;
-- 1. Quyền cho TPCH_VIEWER: Chỉ đọc schema REPORTS
GRANT USAGE ON SCHEMA TPCH_ANALYTICS_DB.REPORTS TO ROLE TPCH_VIEWER;
GRANT
SELECT
    ON ALL TABLES IN SCHEMA TPCH_ANALYTICS_DB.REPORTS TO ROLE TPCH_VIEWER;
GRANT
SELECT
    ON ALL VIEWS IN SCHEMA TPCH_ANALYTICS_DB.REPORTS TO ROLE TPCH_VIEWER;
GRANT
SELECT
    ON FUTURE TABLES IN SCHEMA TPCH_ANALYTICS_DB.REPORTS TO ROLE TPCH_VIEWER;
GRANT
SELECT
    ON FUTURE VIEWS IN SCHEMA TPCH_ANALYTICS_DB.REPORTS TO ROLE TPCH_VIEWER;
-- 2. Quyền cho TPCH_ANALYST: Đọc schema ANALYTICS, REPORTS và gọi UDFs
    GRANT USAGE ON SCHEMA TPCH_ANALYTICS_DB.ANALYTICS TO ROLE TPCH_ANALYST;
GRANT USAGE ON SCHEMA TPCH_ANALYTICS_DB.UDFS TO ROLE TPCH_ANALYST;
GRANT
SELECT
    ON ALL TABLES IN SCHEMA TPCH_ANALYTICS_DB.ANALYTICS TO ROLE TPCH_ANALYST;
GRANT
SELECT
    ON ALL VIEWS IN SCHEMA TPCH_ANALYTICS_DB.ANALYTICS TO ROLE TPCH_ANALYST;
GRANT
SELECT
    ON FUTURE TABLES IN SCHEMA TPCH_ANALYTICS_DB.ANALYTICS TO ROLE TPCH_ANALYST;
GRANT
SELECT
    ON FUTURE VIEWS IN SCHEMA TPCH_ANALYTICS_DB.ANALYTICS TO ROLE TPCH_ANALYST;
GRANT USAGE ON ALL FUNCTIONS IN SCHEMA TPCH_ANALYTICS_DB.UDFS TO ROLE TPCH_ANALYST;
GRANT USAGE ON FUTURE FUNCTIONS IN SCHEMA TPCH_ANALYTICS_DB.UDFS TO ROLE TPCH_ANALYST;
-- 3. Quyền cho TPCH_DEVELOPER: Toàn quyền thao tác dữ liệu (CRUD, Stage, Tasks)
    GRANT ALL PRIVILEGES ON SCHEMA TPCH_ANALYTICS_DB.STAGING TO ROLE TPCH_DEVELOPER;
GRANT ALL PRIVILEGES ON SCHEMA TPCH_ANALYTICS_DB.ANALYTICS TO ROLE TPCH_DEVELOPER;
GRANT ALL PRIVILEGES ON SCHEMA TPCH_ANALYTICS_DB.REPORTS TO ROLE TPCH_DEVELOPER;
GRANT ALL PRIVILEGES ON SCHEMA TPCH_ANALYTICS_DB.UDFS TO ROLE TPCH_DEVELOPER;
-- ---------------------------------------------------------------------
    -- 1.3 TẠO FILE FORMAT VÀ INTERNAL STAGE
    -- ---------------------------------------------------------------------
    USE ROLE TPCH_DEVELOPER;
USE WAREHOUSE TPCH_WH;
USE DATABASE TPCH_ANALYTICS_DB;
USE SCHEMA STAGING;
-- Tạo định dạng file CSV (chuẩn TPC-H thường dùng dấu phân tách | hoặc ,)
    CREATE
    OR REPLACE FILE FORMAT TPCH_CSV_FORMAT TYPE = 'CSV' FIELD_DELIMITER = '|' RECORD_DELIMITER = '\n' SKIP_HEADER = 0 FIELD_OPTIONALLY_ENCLOSED_BY = '"' TRIM_SPACE = TRUE ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE NULL_IF = ('', 'NULL', 'null');
-- Tạo Internal Stage chứa data files
    CREATE
    OR REPLACE STAGE TPCH_DATA_STAGE FILE_FORMAT = TPCH_CSV_FORMAT COMMENT = 'Stage chứa các file dữ liệu thô TPC-H';
    -- ---------------------------------------------------------------------
    -- TỰ SINH DỮ LIỆU VÀO STAGE (THAY THẾ BƯỚC UPLOAD THỦ CÔNG VÌ KHÔNG CÓ FILE CSV)
    -- ---------------------------------------------------------------------
    USE ROLE TPCH_DEVELOPER;
USE WAREHOUSE TPCH_WH;
USE DATABASE TPCH_ANALYTICS_DB;
USE SCHEMA STAGING;
-- Xuất REGION
    COPY INTO @TPCH_DATA_STAGE/region.csv
FROM
    SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION FILE_FORMAT = (
        TYPE = 'CSV' FIELD_DELIMITER = '|' COMPRESSION = NONE
    ) SINGLE = TRUE MAX_FILE_SIZE = 5368709120 OVERWRITE = TRUE;
-- Xuất NATION
    COPY INTO @TPCH_DATA_STAGE/nation.csv
FROM
    SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION FILE_FORMAT = (
        TYPE = 'CSV' FIELD_DELIMITER = '|' COMPRESSION = NONE
    ) SINGLE = TRUE MAX_FILE_SIZE = 5368709120 OVERWRITE = TRUE;
-- Xuất SUPPLIER
    COPY INTO @TPCH_DATA_STAGE/supplier.csv
FROM
    SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.SUPPLIER FILE_FORMAT = (
        TYPE = 'CSV' FIELD_DELIMITER = '|' COMPRESSION = NONE
    ) SINGLE = TRUE MAX_FILE_SIZE = 5368709120 OVERWRITE = TRUE;
-- Xuất CUSTOMER
    COPY INTO @TPCH_DATA_STAGE/customer.csv
FROM
    SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER FILE_FORMAT = (
        TYPE = 'CSV' FIELD_DELIMITER = '|' COMPRESSION = NONE
    ) SINGLE = TRUE MAX_FILE_SIZE = 5368709120 OVERWRITE = TRUE;
-- Xuất PART
    COPY INTO @TPCH_DATA_STAGE/part.csv
FROM
    SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PART FILE_FORMAT = (
        TYPE = 'CSV' FIELD_DELIMITER = '|' COMPRESSION = NONE
    ) SINGLE = TRUE MAX_FILE_SIZE = 5368709120 OVERWRITE = TRUE;
-- Xuất PARTSUPP
    COPY INTO @TPCH_DATA_STAGE/partsupp.csv
FROM
    SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.PARTSUPP FILE_FORMAT = (
        TYPE = 'CSV' FIELD_DELIMITER = '|' COMPRESSION = NONE
    ) SINGLE = TRUE MAX_FILE_SIZE = 5368709120 OVERWRITE = TRUE;
-- Xuất ORDERS
    COPY INTO @TPCH_DATA_STAGE/orders.csv
FROM
    SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS FILE_FORMAT = (
        TYPE = 'CSV' FIELD_DELIMITER = '|' COMPRESSION = NONE
    ) SINGLE = TRUE MAX_FILE_SIZE = 5368709120 OVERWRITE = TRUE;
-- Xuất LINEITEM (bảng nặng nhất, chạy mất khoảng 15-20s)
    COPY INTO @TPCH_DATA_STAGE/lineitem.csv
FROM
    SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM FILE_FORMAT = (
        TYPE = 'CSV' FIELD_DELIMITER = '|' COMPRESSION = NONE
    ) SINGLE = TRUE MAX_FILE_SIZE = 5368709120 OVERWRITE = TRUE;
-- Kiểm tra danh sách file trên stage
    LIST @TPCH_DATA_STAGE;
-- ---------------------------------------------------------------------
    -- 1.4 TẠO CÁC BẢNG RAW (BRONZE LAYER)
    -- ---------------------------------------------------------------------
    -- Bảng 1: REGION
    CREATE
    OR REPLACE TABLE REGION (
        R_REGIONKEY NUMBER(38, 0),
        R_NAME VARCHAR(25),
        R_COMMENT VARCHAR(152)
    );
-- Bảng 2: NATION
    CREATE
    OR REPLACE TABLE NATION (
        N_NATIONKEY NUMBER(38, 0),
        N_NAME VARCHAR(25),
        N_REGIONKEY NUMBER(38, 0),
        N_COMMENT VARCHAR(152)
    );
-- Bảng 3: CUSTOMER
    CREATE
    OR REPLACE TABLE CUSTOMER (
        C_CUSTKEY NUMBER(38, 0),
        C_NAME VARCHAR(25),
        C_ADDRESS VARCHAR(40),
        C_NATIONKEY NUMBER(38, 0),
        C_PHONE VARCHAR(15),
        C_ACCTBAL NUMBER(12, 2),
        C_MKTSEGMENT VARCHAR(10),
        C_COMMENT VARCHAR(117)
    );
-- Bảng 4: SUPPLIER
    CREATE
    OR REPLACE TABLE SUPPLIER (
        S_SUPPKEY NUMBER(38, 0),
        S_NAME VARCHAR(25),
        S_ADDRESS VARCHAR(40),
        S_NATIONKEY NUMBER(38, 0),
        S_PHONE VARCHAR(15),
        S_ACCTBAL NUMBER(12, 2),
        S_COMMENT VARCHAR(101)
    );
-- Bảng 5: PART
    CREATE
    OR REPLACE TABLE PART (
        P_PARTKEY NUMBER(38, 0),
        P_NAME VARCHAR(55),
        P_MFGR VARCHAR(25),
        P_BRAND VARCHAR(10),
        P_TYPE VARCHAR(25),
        P_SIZE NUMBER(38, 0),
        P_CONTAINER VARCHAR(10),
        P_RETAILPRICE NUMBER(12, 2),
        P_COMMENT VARCHAR(23)
    );
-- Bảng 6: PARTSUPP
    CREATE
    OR REPLACE TABLE PARTSUPP (
        PS_PARTKEY NUMBER(38, 0),
        PS_SUPPKEY NUMBER(38, 0),
        PS_AVAILQTY NUMBER(38, 0),
        PS_SUPPLYCOST NUMBER(12, 2),
        PS_COMMENT VARCHAR(199)
    );
-- Bảng 7: ORDERS
    CREATE
    OR REPLACE TABLE ORDERS (
        O_ORDERKEY NUMBER(38, 0),
        O_CUSTKEY NUMBER(38, 0),
        O_ORDERSTATUS VARCHAR(1),
        O_TOTALPRICE NUMBER(12, 2),
        O_ORDERDATE DATE,
        O_ORDERPRIORITY VARCHAR(15),
        O_CLERK VARCHAR(15),
        O_SHIPPRIORITY NUMBER(38, 0),
        O_COMMENT VARCHAR(79)
    );
-- Bảng 8: LINEITEM
    CREATE
    OR REPLACE TABLE LINEITEM (
        L_ORDERKEY NUMBER(38, 0),
        L_PARTKEY NUMBER(38, 0),
        L_SUPPKEY NUMBER(38, 0),
        L_LINENUMBER NUMBER(38, 0),
        L_QUANTITY NUMBER(12, 2),
        L_EXTENDEDPRICE NUMBER(12, 2),
        L_DISCOUNT NUMBER(12, 2),
        L_TAX NUMBER(12, 2),
        L_RETURNFLAG VARCHAR(1),
        L_LINESTATUS VARCHAR(1),
        L_SHIPDATE DATE,
        L_COMMITDATE DATE,
        L_RECEIPTDATE DATE,
        L_SHIPINSTRUCT VARCHAR(25),
        L_SHIPMODE VARCHAR(10),
        L_COMMENT VARCHAR(44)
    );
-- ---------------------------------------------------------------------
    -- 1.5 LOAD DỮ LIỆU TỪ STAGE VÀO TABLES
    -- ---------------------------------------------------------------------
    COPY INTO REGION
FROM
    @TPCH_DATA_STAGE FILES = ('region.csv') FILE_FORMAT = (FORMAT_NAME = TPCH_CSV_FORMAT) ON_ERROR = 'CONTINUE';
COPY INTO NATION
FROM
    @TPCH_DATA_STAGE FILES = ('nation.csv') FILE_FORMAT = (FORMAT_NAME = TPCH_CSV_FORMAT) ON_ERROR = 'CONTINUE';
COPY INTO SUPPLIER
FROM
    @TPCH_DATA_STAGE FILES = ('supplier.csv') FILE_FORMAT = (FORMAT_NAME = TPCH_CSV_FORMAT) ON_ERROR = 'CONTINUE';
COPY INTO CUSTOMER
FROM
    @TPCH_DATA_STAGE FILES = ('customer.csv') FILE_FORMAT = (FORMAT_NAME = TPCH_CSV_FORMAT) ON_ERROR = 'CONTINUE';
COPY INTO PART
FROM
    @TPCH_DATA_STAGE FILES = ('part.csv') FILE_FORMAT = (FORMAT_NAME = TPCH_CSV_FORMAT) ON_ERROR = 'CONTINUE';
COPY INTO PARTSUPP
FROM
    @TPCH_DATA_STAGE FILES = ('partsupp.csv') FILE_FORMAT = (FORMAT_NAME = TPCH_CSV_FORMAT) ON_ERROR = 'CONTINUE';
COPY INTO ORDERS
FROM
    @TPCH_DATA_STAGE FILES = ('orders.csv') FILE_FORMAT = (FORMAT_NAME = TPCH_CSV_FORMAT) ON_ERROR = 'CONTINUE';
COPY INTO LINEITEM
FROM
    @TPCH_DATA_STAGE FILES = ('lineitem.csv') FILE_FORMAT = (FORMAT_NAME = TPCH_CSV_FORMAT) ON_ERROR = 'CONTINUE';
-- ---------------------------------------------------------------------
    -- 1.6 KIỂM TRA DỮ LIỆU & PHÂN QUYỀN (SANITY CHECKS)
    -- ---------------------------------------------------------------------
    -- Đếm số dòng trong từng bảng Bronze layer
SELECT
    'REGION' AS TABLE_NAME,
    COUNT(*) AS ROW_COUNT
FROM
    REGION
UNION ALL
SELECT
    'NATION',
    COUNT(*)
FROM
    NATION
UNION ALL
SELECT
    'SUPPLIER',
    COUNT(*)
FROM
    SUPPLIER
UNION ALL
SELECT
    'CUSTOMER',
    COUNT(*)
FROM
    CUSTOMER
UNION ALL
SELECT
    'PART',
    COUNT(*)
FROM
    PART
UNION ALL
SELECT
    'PARTSUPP',
    COUNT(*)
FROM
    PARTSUPP
UNION ALL
SELECT
    'ORDERS',
    COUNT(*)
FROM
    ORDERS
UNION ALL
SELECT
    'LINEITEM',
    COUNT(*)
FROM
    LINEITEM;
